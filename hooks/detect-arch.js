#!/usr/bin/env node
// arc-code-flows -- Claude Code SessionStart hook.
// Detects a .arch/manifest.json (written by the separate `arc-code-cli` npm
// package) in the current project and, if present, nudges Claude to use it
// as reference instead of re-reading source for flow/function/class/module
// questions. Project-agnostic: this hook only checks for the file's
// existence and reads its generic shape (analyzedFiles.length) -- it has no
// knowledge of what any particular project's routes/classes/modules are
// named.
//
// Only checks process.cwd() directly (no walking up parent directories) --
// Claude Code's session cwd is normally the project root already, and
// walking up risks picking up an unrelated ancestor project's .arch/.

const fs = require('fs');
const path = require('path');

const manifestPath = path.join(process.cwd(), '.arch', 'manifest.json');

if (!fs.existsSync(manifestPath)) {
  process.exit(0);
}

let fileCount = null;
try {
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  fileCount = Array.isArray(manifest.analyzedFiles) ? manifest.analyzedFiles.length : null;
} catch (e) {
  // Malformed manifest -- still worth flagging, just without the file count.
}

const summary = fileCount !== null ? ` (${fileCount} source files analyzed last run)` : '';

const output = `This project has Arc Code static-analysis diagrams at .arch/${summary} -- generated by the separate \`arc-code-cli\` npm package (no AI, no code execution; may be stale if source changed since the last run).

Treat .arch/ (root files and domains/) as the source of truth for this project's current architecture and flows -- over your own inference from skimming code. Before re-reading source to answer a question about a route, function, class, or module's flow, structure, call graph, or complexity: read .arch/manifest.json's "index" field first. It maps this project's own exact names (whatever its own routes/classes/functions/modules are called -- a route as "METHOD /path", a method as "ClassName.method", a class by name, a module by its path) straight to the one .mmd mini-flow file that answers it -- read only that file instead of re-parsing source. If the thing asked about isn't in the index, fall back to reading source normally; never claim the diagrams show something they don't.

Before implementing anything that would add, remove, or move a route, function, class, or dependency: describe the proposed end-state as JSON (schema/proposal.schema.json) and run \`npx arc-code-cli render-proposal <file.json>\` to render it into .arch/.temp/ -- never hand-write the .mmd. List what each file shows and explicitly ask for approval -- only after a yes does any real source file get touched. Load the arc-code-flows skill for the full convention.`;

process.stdout.write(output);
process.exit(0);
